"""Split the upstream chart showcase into a hub-and-spoke set of Jekyll pages.

The showcase is generated by TerraFluent.Chart.Reporting itself and mirrored
into this repo by mirror-docs.sh, so it cannot be hand-edited: the next mirror
run would overwrite the edits. This script is the site-side generator. It reads
the mirrored source once and emits every derived page, so re-mirroring the
library and re-running this produces the same split against the new specimens.

Input
  _showcase-source/showcase.html   upstream, verbatim (written by mirror-docs.sh)
  docs/chart/chart-types.md        upstream docs; the C# snippets are lifted from
                                   here rather than written by hand, so they are
                                   always the library's real API
  _data/chart_types.yml            the hand-written prose

Output
  chart/showcase/index.html        the hub: a linked index, no specimens
  chart/types/<slug>/index.html    27 chart-type pages
  chart/features/<slug>/index.html  8 feature pages
  chart/cookbook/index.html        the recipe cookbook
  _data/chart_spokes.yml           the generated URL list, consumed by the hub
                                   layout and by the llms.txt block

Every specimen SVG is moved, never copied and never re-rendered, so each one
lives at exactly one URL. Run with --check to verify without writing.
"""

